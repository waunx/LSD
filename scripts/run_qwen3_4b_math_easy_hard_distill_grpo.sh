#!/usr/bin/env bash
# Easy/hard routed training for math:
# easy prompts -> teacher distillation, hard prompts -> GRPO.

set -xeuo pipefail

# ---- user-adjustable ----
DEVICE=${DEVICE:-gpu}
INFER_BACKEND=${INFER_BACKEND:-vllm}
export CUDA_DEVICE_ORDER=PCI_BUS_ID
export CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}
export VLLM_USE_V1=1
export HYDRA_FULL_ERROR=1
export RAY_DEDUP_LOGS=0
FORCE_LOCAL_RAY=1
if [[ "${FORCE_LOCAL_RAY}" == "1" ]]; then
    unset RAY_ADDRESS
fi

MODEL_PATH="/data/wx_data/models/Qwen3-4B-Base"
TEACHER_CKPT_DIR="/data/wx_data/verl-lsd/checkpoints/length_scaling/0609-qwen3_4b_base-math-4k-3/global_step_200/actor"
TEACHER_MODEL_PATH="/data/wx_data/verl-lsd/checkpoints/length_scaling/0609-qwen3_4b_base-math-4k-3/global_step_200/actor_hf"
# Generated by scripts/run_qwen3_4b_math_teacher_offline_labels.sh.
OFFLINE_LABEL_FILE="/data/wx_data/verl-lsd/outputs/easy_hard_offline_labels/qwen3_4b_teacher_4k_train_offline_labels-5/validation_data/0.jsonl"

TRAIN_FILE="['/data/wx_data/datasets/OPD/DAPO-Math-17k/data/dapo-math-17k.parquet']"
TEST_FILE="['/data/wx_data/datasets/LSD/aime.parquet','/data/wx_data/datasets/LSD/amc.parquet','/data/wx_data/datasets/LSD/math.parquet']"

NNODES=${NNODES:-1}
# 8xA100 total by default: 4 GPUs for actor/rollout + 4 GPUs for the frozen teacher.
# Resource demand is trainer.n_gpus_per_node + distillation.n_gpus_per_node.
NGPUS_PER_NODE=${NGPUS_PER_NODE:-4}
TEACHER_NNODES=${TEACHER_NNODES:-1}
TEACHER_WORLD_SIZE=${TEACHER_WORLD_SIZE:-4}

TRAIN_BATCH_SIZE=256
PPO_MINI_BATCH_SIZE=128
PPO_MICRO_BATCH_SIZE_PER_GPU=2
LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=2
DATA_SEED=42
TRAIN_MAX_SAMPLES=51200
MAX_PROMPT_LENGTH=2048
MAX_RESPONSE_LENGTH=12288
MAX_TOKEN_LEN_PER_GPU=$((MAX_PROMPT_LENGTH + MAX_RESPONSE_LENGTH + 1))
MAX_MODEL_LEN=$((MAX_PROMPT_LENGTH + MAX_RESPONSE_LENGTH + 1))
DEFAULT_MAX_NUM_BATCHED_TOKENS=${DEFAULT_MAX_NUM_BATCHED_TOKENS:-16384}
if (( DEFAULT_MAX_NUM_BATCHED_TOKENS < MAX_MODEL_LEN )); then
    DEFAULT_MAX_NUM_BATCHED_TOKENS=${MAX_MODEL_LEN}
fi
MAX_NUM_BATCHED_TOKENS=${MAX_NUM_BATCHED_TOKENS:-${DEFAULT_MAX_NUM_BATCHED_TOKENS}}
MAX_NUM_SEQS=${MAX_NUM_SEQS:-384}

ACTOR_LR=1e-6
ALPHA_EASY=1.0
ALPHA_HARD=1.0
KL_LOSS_COEF=1e-5
ENTROPY_COEFF=0.0

ROLLOUT_TP=${ROLLOUT_TP:-4}
ROLLOUT_GPU_MEM_UTIL=${ROLLOUT_GPU_MEM_UTIL:-0.62}
ROLLOUT_N=${ROLLOUT_N:-8}
VAL_N=${VAL_N:-8}
ROLLOUT_ENFORCE_EAGER=${ROLLOUT_ENFORCE_EAGER:-False}
ROLLOUT_TEMPERATURE=1.0
ROLLOUT_TOP_P=1.0
ROLLOUT_TOP_K=-1
VAL_DO_SAMPLE=False
VAL_TEMPERATURE=0
VAL_TOP_P=1.0
VAL_TOP_K=-1

TEACHER_TP=${TEACHER_TP:-4}
TEACHER_GPU_MEM_UTIL=${TEACHER_GPU_MEM_UTIL:-0.50}
TEACHER_MAX_NUM_SEQS=${TEACHER_MAX_NUM_SEQS:-384}
OPD_MODE=${OPD_MODE:-supervised}
if [[ -z "${DISTILLATION_LOSS_MODE:-}" ]]; then
    case "${OPD_MODE}" in
        supervised)
            DISTILLATION_LOSS_MODE=forward_kl_topk
            ;;
        rl)
            DISTILLATION_LOSS_MODE=k3
            ;;
        *)
            echo "Unsupported OPD_MODE=${OPD_MODE}. Expected 'supervised' or 'rl'." >&2
            exit 1
            ;;
    esac
fi
RL_DISTILLATION_REWARD_LOSS_MODE=${RL_DISTILLATION_REWARD_LOSS_MODE:-k3}
DISTILLATION_TOPK=32
USE_POLICY_GRADIENT=False

# `offline`：读取 teacher rollout JSONL文件
# `online`：用当前 policy rollout 组内 `acc` 判定
: "${EASY_HARD_MODE:?Set EASY_HARD_MODE=online or EASY_HARD_MODE=offline via the wrapper script.}"
EASY_THRESHOLD=0.75
OFFLINE_MISSING_POLICY=online

PROJECT_NAME=length_scaling
if [[ "${EASY_HARD_MODE}" == "offline" ]]; then
    EXPERIMENT_NAME=qwen3_4b_easy_distill_hard_grpo_12k_offline
else
    EXPERIMENT_NAME=qwen3_4b_easy_distill_hard_grpo_12k_online
fi
VALIDATION_DATA_DIR="/data/wx_data/verl-lsd/outputs/${EXPERIMENT_NAME}/validation_data"
# Keep this path short: Ray creates AF_UNIX sockets under it, and Linux limits
# the full socket path to 107 bytes.
RAY_TMPDIR="/tmp/ray_opd_12k"
ROLLOUT_DATA_DIR=""
SAVE_FREQ=20
TEST_FREQ=10
TOTAL_EPOCHS=3
TOTAL_TRAINING_STEPS=200
MIN_FREE_GB=${MIN_FREE_GB:-200}

# ---- end user-adjustable ----

check_free_space() {
    local path=$1
    local min_gb=$2
    local available_kb
    available_kb=$(df -Pk "${path}" | awk 'NR == 2 {print $4}')
    local available_gb=$((available_kb / 1024 / 1024))
    if (( available_gb < min_gb )); then
        echo "Not enough free disk space for ${path}: ${available_gb}GB available, need at least ${min_gb}GB." >&2
        echo "Free checkpoints or set MIN_FREE_GB to a lower value if this is intentional." >&2
        exit 1
    fi
    echo "Free disk space for ${path}: ${available_gb}GB (required >= ${min_gb}GB)."
}

mkdir -p "${RAY_TMPDIR}" logs
mkdir -p "${VALIDATION_DATA_DIR}"
check_free_space "${VALIDATION_DATA_DIR}" "${MIN_FREE_GB}"
check_free_space "${RAY_TMPDIR}" 20

case "${DEVICE}" in
    gpu)
        ;;
    npu)
        export VLLM_USE_V1=1
        export TASK_QUEUE_ENABLE=2
        export CPU_AFFINITY_CONF=1
        export LD_PRELOAD="/usr/lib/aarch64-linux-gnu/libjemalloc.so.2${LD_PRELOAD:+:$LD_PRELOAD}"
        NGPUS_PER_NODE=16
        ROLLOUT_GPU_MEM_UTIL=0.85
        ;;
    *)
        echo "Unsupported DEVICE=${DEVICE}. Expected 'gpu' or 'npu'." >&2
        exit 1
        ;;
esac

if [[ ! -d "${TEACHER_MODEL_PATH}" ]]; then
    echo "TEACHER_MODEL_PATH=${TEACHER_MODEL_PATH} does not exist." >&2
    echo "Export the 4K RL checkpoint first, for example:" >&2
    echo "python3 -m verl.model_merger merge --backend fsdp --local_dir ${TEACHER_CKPT_DIR} --target_dir ${TEACHER_MODEL_PATH}" >&2
    exit 1
fi

DATA=(
    algorithm.adv_estimator=grpo
    algorithm.use_kl_in_reward=False
    "data.train_files=${TRAIN_FILE}"
    "data.val_files=${TEST_FILE}"
    data.train_batch_size=${TRAIN_BATCH_SIZE}
    data.train_max_samples=${TRAIN_MAX_SAMPLES}
    data.shuffle=True
    data.seed=${DATA_SEED}
    data.max_prompt_length=${MAX_PROMPT_LENGTH}
    data.max_response_length=${MAX_RESPONSE_LENGTH}
    data.filter_overlong_prompts=False
    data.truncation='left'
)

MODEL=(
    actor_rollout_ref.model.path=${MODEL_PATH}
    actor_rollout_ref.model.use_remove_padding=True
    actor_rollout_ref.model.enable_gradient_checkpointing=True
)

ACTOR=(
    actor_rollout_ref.actor.optim.lr=${ACTOR_LR}
    actor_rollout_ref.actor.ppo_mini_batch_size=${PPO_MINI_BATCH_SIZE}
    actor_rollout_ref.actor.ppo_micro_batch_size_per_gpu=${PPO_MICRO_BATCH_SIZE_PER_GPU}
    actor_rollout_ref.actor.use_kl_loss=True
    actor_rollout_ref.actor.kl_loss_coef=${KL_LOSS_COEF}
    actor_rollout_ref.actor.kl_loss_type=low_var_kl
    actor_rollout_ref.actor.entropy_coeff=${ENTROPY_COEFF}
    actor_rollout_ref.actor.fsdp_config.param_offload=False
    actor_rollout_ref.actor.fsdp_config.optimizer_offload=False
    actor_rollout_ref.actor.fsdp_config.model_dtype=bfloat16
    actor_rollout_ref.actor.ppo_max_token_len_per_gpu=${MAX_TOKEN_LEN_PER_GPU}
    actor_rollout_ref.actor.use_dynamic_bsz=True
)

ROLLOUT=(
    actor_rollout_ref.rollout.log_prob_micro_batch_size_per_gpu=${LOG_PROB_MICRO_BATCH_SIZE_PER_GPU}
    actor_rollout_ref.rollout.tensor_model_parallel_size=${ROLLOUT_TP}
    actor_rollout_ref.rollout.name=${INFER_BACKEND}
    actor_rollout_ref.rollout.gpu_memory_utilization=${ROLLOUT_GPU_MEM_UTIL}
    actor_rollout_ref.rollout.do_sample=True
    actor_rollout_ref.rollout.temperature=${ROLLOUT_TEMPERATURE}
    actor_rollout_ref.rollout.top_p=${ROLLOUT_TOP_P}
    actor_rollout_ref.rollout.top_k=${ROLLOUT_TOP_K}
    actor_rollout_ref.rollout.enable_chunked_prefill=False
    actor_rollout_ref.rollout.enforce_eager=${ROLLOUT_ENFORCE_EAGER}
    actor_rollout_ref.rollout.free_cache_engine=True
    actor_rollout_ref.rollout.log_prob_use_dynamic_bsz=True
    actor_rollout_ref.rollout.log_prob_max_token_len_per_gpu=${MAX_TOKEN_LEN_PER_GPU}
    actor_rollout_ref.rollout.max_model_len=${MAX_MODEL_LEN}
    actor_rollout_ref.rollout.max_num_seqs=${MAX_NUM_SEQS}
    actor_rollout_ref.rollout.max_num_batched_tokens=${MAX_NUM_BATCHED_TOKENS}
    actor_rollout_ref.rollout.checkpoint_engine.update_weights_bucket_megabytes=4096
    actor_rollout_ref.rollout.n=${ROLLOUT_N}
    actor_rollout_ref.rollout.val_kwargs.n=${VAL_N}
    actor_rollout_ref.rollout.val_kwargs.do_sample=${VAL_DO_SAMPLE}
    actor_rollout_ref.rollout.val_kwargs.temperature=${VAL_TEMPERATURE}
    actor_rollout_ref.rollout.val_kwargs.top_p=${VAL_TOP_P}
    actor_rollout_ref.rollout.val_kwargs.top_k=${VAL_TOP_K}
)

REF=(
    actor_rollout_ref.ref.log_prob_micro_batch_size_per_gpu=${LOG_PROB_MICRO_BATCH_SIZE_PER_GPU}
    actor_rollout_ref.ref.fsdp_config.param_offload=True
    actor_rollout_ref.ref.fsdp_config.model_dtype=bfloat16
    actor_rollout_ref.ref.log_prob_use_dynamic_bsz=True
    actor_rollout_ref.ref.log_prob_max_token_len_per_gpu=${MAX_TOKEN_LEN_PER_GPU}
)

DISTILLATION=(
    distillation.enabled=True
    distillation.n_gpus_per_node=${TEACHER_WORLD_SIZE}
    distillation.nnodes=${TEACHER_NNODES}
    distillation.teacher_models.teacher_model.model_path=${TEACHER_MODEL_PATH}
    distillation.teacher_models.teacher_model.inference.tensor_model_parallel_size=${TEACHER_TP}
    distillation.teacher_models.teacher_model.inference.name=${INFER_BACKEND}
    distillation.teacher_models.teacher_model.inference.gpu_memory_utilization=${TEACHER_GPU_MEM_UTIL}
    distillation.teacher_models.teacher_model.inference.max_model_len=${MAX_MODEL_LEN}
    distillation.teacher_models.teacher_model.inference.max_num_seqs=${TEACHER_MAX_NUM_SEQS}
    distillation.teacher_models.teacher_model.inference.max_num_batched_tokens=${MAX_NUM_BATCHED_TOKENS}
    distillation.teacher_models.teacher_model.inference.temperature=1.0
    distillation.distillation_loss.loss_mode=${DISTILLATION_LOSS_MODE}
    distillation.distillation_loss.opd_mode=${OPD_MODE}
    distillation.distillation_loss.rl_reward_loss_mode=${RL_DISTILLATION_REWARD_LOSS_MODE}
    distillation.distillation_loss.topk=${DISTILLATION_TOPK}
    distillation.distillation_loss.use_task_rewards=True
    distillation.distillation_loss.distillation_loss_coef=${ALPHA_EASY}
    distillation.distillation_loss.hard_loss_coef=${ALPHA_HARD}
    distillation.distillation_loss.use_policy_gradient=${USE_POLICY_GRADIENT}
    distillation.distillation_loss.loss_max_clamp=10.0
    distillation.distillation_loss.log_prob_min_clamp=-10.0
    distillation.easy_hard_split.enabled=True
    distillation.easy_hard_split.mode=${EASY_HARD_MODE}
    distillation.easy_hard_split.accuracy_threshold=${EASY_THRESHOLD}
    distillation.easy_hard_split.score_key=acc
    distillation.easy_hard_split.offline_label_path=${OFFLINE_LABEL_FILE}
    distillation.easy_hard_split.offline_missing_policy=${OFFLINE_MISSING_POLICY}
)

TRAINER=(
    trainer.critic_warmup=0
    trainer.logger='["console","swanlab"]'
    trainer.project_name=${PROJECT_NAME}
    trainer.experiment_name=${EXPERIMENT_NAME}
    trainer.validation_data_dir=${VALIDATION_DATA_DIR}
    trainer.n_gpus_per_node=${NGPUS_PER_NODE}
    trainer.nnodes=${NNODES}
    trainer.save_freq=${SAVE_FREQ}
    trainer.test_freq=${TEST_FREQ}
    trainer.val_before_train=True
    trainer.total_epochs=${TOTAL_EPOCHS}
    trainer.total_training_steps=${TOTAL_TRAINING_STEPS}
    +ray_kwargs.ray_init._temp_dir=${RAY_TMPDIR}
)

EXTRA=()
if [[ -n "${ROLLOUT_DATA_DIR}" ]]; then
    EXTRA+=(trainer.rollout_data_dir=${ROLLOUT_DATA_DIR})
fi

python3 -m verl.trainer.main_ppo \
    "${DATA[@]}" \
    "${MODEL[@]}" \
    "${ACTOR[@]}" \
    "${ROLLOUT[@]}" \
    "${REF[@]}" \
    "${DISTILLATION[@]}" \
    "${TRAINER[@]}" \
    "${EXTRA[@]}" \
    "$@"
